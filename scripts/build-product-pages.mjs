/* pull CATALOG out of store.js without importing the browser globals it also defines */
function loadCatalog() {
  const src = readFileSync(join(ROOT, "store.js"), "utf8");
  const start = src.indexOf("const CATALOG");
  const end = src.indexOf("];", start) + 2;
  const body = src.slice(src.indexOf("[", start), end);
  return new Function(`return ${body}`)();
}

const CAT_SINGULAR = { Serums: "Serum", Creams: "Cream", Cleansers: "Cleanser", Oils: "Oil", Masks: "Mask", Sets: "Set" };
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function specRows(spec) {
  return Object.entries(spec)
    .map(([k, v]) => `        <div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`)
    .join("\n");
}

/* up to three siblings in the same category, in catalog order, excluding self */
function siblings(catalog, p) {
  return catalog.filter((q) => q.cat === p.cat && q.id !== p.id).slice(0, 3);
}

function siblingCards(sibs) {
  return sibs
    .map(
      (s) => `        <a class="rel-card" href="${s.id}.html">
          <div class="rel-figure"><img src="../assets/${esc(s.img)}" alt="${esc(s.name)}" loading="lazy" /></div>
          <div class="rel-body"><span class="rel-name">${esc(s.name)}</span><span class="rel-price">$${s.price}</span></div>
          <div class="rel-note">${esc(s.note)}</div>
        </a>`
    )
    .join("\n");
}


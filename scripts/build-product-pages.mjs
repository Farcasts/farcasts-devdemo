function main() {
  const catalog = loadCatalog();
  const outDir = join(ROOT, "products");
  mkdirSync(outDir, { recursive: true });
  for (const p of catalog) writeFileSync(join(outDir, `${p.id}.html`), page(p, catalog));
  console.log(`Wrote ${catalog.length} product pages to products/`);
}

main();
